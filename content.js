/* =========================================================
   END BATTLE AFTER DEATH
   ========================================================= */

function endBattleAfterDeath(
    enemy
) {

    enemy.health =
        0;

    enemy.active =
        false;

    enemy.defeated =
        true;


    G.currentEnemy =
        null;

    G.battleOpen =
        false;

    G.mode =
        "explore";


    document.getElementById(
        "battleScreen"
    ).style.display =
        "none";


    P.stamina =
        Math.min(
            P.maxStamina,
            P.stamina + 20
        );


    PG.updateHUD();

}


/* =========================================================
   DEER MAN SPECIAL ENCOUNTER
   ========================================================= */

function spawnDeerMan() {

    const existing =
        enemies.find(
            enemy =>
                enemy.enemyType ===
                "deerMan"
        );


    if (existing)
        return existing;


    return PG.spawnMonster(
        "deerMan",
        3100,
        2500
    );

}


