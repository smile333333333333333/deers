let currentCutscene = null;

let cutsceneIndex = 0;


function playCutscene(
    scenes,
    finished
) {

    if (
        !Array.isArray(
            scenes
        ) ||
        scenes.length === 0
    ) {

        if (finished)
            finished();

        return;

    }

    G.mode =
        "cutscene";

    currentCutscene =
        scenes;

    cutsceneIndex =
        0;

    const screen =
        document.getElementById(
            "cutscene"
        );

    screen.style.display =
        "flex";

    showCutsceneFrame();

}


function showCutsceneFrame() {

    const scene =
        currentCutscene[
            cutsceneIndex
        ];

    const text =
        document.getElementById(
            "cutsceneText"
        );

    text.textContent =
        scene.text;


    if (
        scene.sound
    ) {

        playSceneSound(
            scene.sound
        );

    }

}


function playSceneSound(
    sound
) {

    switch (sound) {

        case "creature":
            AudioSystem.creature();
            break;

        case "scare":
            AudioSystem.scare();
            break;

        case "noise":
            AudioSystem.noise(
                0.5,
                0.06
            );
            break;

        case "death":
            AudioSystem.death();
            break;

        default:
            AudioSystem.tone(
                100,
                0.2,
                "triangle",
                0.03
            );

    }

}


document
    .getElementById(
        "cutsceneButton"
    )
    .addEventListener(
        "click",
        advanceCutscene
    );


function advanceCutscene() {

    cutsceneIndex++;

    if (
        cutsceneIndex >=
        currentCutscene.length
    ) {

        finishCutscene();

        return;

    }

    showCutsceneFrame();

}


function finishCutscene() {

    document.getElementById(
        "cutscene"
    ).style.display =
        "none";

    G.mode =
        "explore";

    if (
        typeof G.cutsceneFinished ===
        "function"
    ) {

        const callback =
            G.cutsceneFinished;

        G.cutsceneFinished =
            null;

        callback();

    }

}


